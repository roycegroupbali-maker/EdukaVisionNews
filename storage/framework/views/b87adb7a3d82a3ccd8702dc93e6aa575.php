    <h1 class="display" style="font-size:clamp(28px,4vw,44px); line-height:1.15; margin:14px 0 20px;">Pedoman Media Siber</h1>

    <div class="article-body" style="font-family:'Fraunces', serif; font-size:17px; line-height:1.85; color:var(--ink,#1a1a1a);">

      <p style="margin-bottom:20px;">Kemerdekaan berpendapat, kemerdekaan berekspresi, dan kemerdekaan pers adalah hak asasi manusia yang dilindungi Pancasila, Undang-Undang Dasar 1945, dan Deklarasi Universal Hak Asasi Manusia PBB. Keberadaan media siber di Indonesia juga merupakan bagian dari kemerdekaan berpendapat, kemerdekaan berekspresi, dan kemerdekaan pers.</p>

      <p style="margin-bottom:30px;">Media siber memiliki karakter khusus sehingga memerlukan pedoman agar pengelolaannya dapat dilaksanakan secara profesional, memenuhi fungsi, hak, dan kewajibannya sesuai Undang-Undang Nomor 40 Tahun 1999 tentang Pers dan Kode Etik Jurnalistik. Untuk itu Dewan Pers bersama organisasi pers, pengelola media siber, dan masyarakat menyusun Pedoman Pemberitaan Media Siber sebagai berikut, yang menjadi acuan pengelolaan redaksi EdukaVisionNews.</p>

      <h2 style="font-family:'Fraunces', serif; font-size:23px; margin:32px 0 12px;">1. Ruang Lingkup</h2>
      <p style="margin-bottom:20px;">Isi Buatan Pengguna (User Generated Content) adalah segala isi yang dibuat dan/atau dipublikasikan oleh pengguna media siber, antara lain artikel, gambar, komentar, suara, video, dan berbagai bentuk unggahan yang melekat pada media siber, seperti blog, forum, komentar pembaca atau pemirsa, dan bentuk lain.</p>

      <h2 style="font-family:'Fraunces', serif; font-size:23px; margin:32px 0 12px;">2. Verifikasi dan Keberimbangan Berita</h2>
      <ul style="margin-bottom:20px; padding-left:22px;">
        <li style="margin-bottom:10px;">Pada prinsipnya setiap berita harus melalui verifikasi.</li>
        <li style="margin-bottom:10px;">Berita yang dapat merugikan pihak lain memerlukan verifikasi pada berita yang sama untuk memenuhi prinsip akurasi dan keberimbangan.</li>
        <li style="margin-bottom:10px;">
          Ketentuan di atas dikecualikan dengan syarat: berita benar-benar mengandung kepentingan publik yang mendesak; sumber berita pertama jelas identitasnya, kredibel, dan kompeten; subjek berita yang harus dikonfirmasi tidak diketahui keberadaannya atau tidak dapat diwawancarai; dan media menjelaskan kepada pembaca bahwa berita tersebut masih memerlukan verifikasi lebih lanjut, dimuat pada bagian akhir berita dalam kurung dan huruf miring.
        </li>
        <li style="margin-bottom:10px;">Setelah memuat berita sesuai ketentuan tersebut, media wajib meneruskan upaya verifikasi, dan hasil verifikasi dicantumkan pada berita pemutakhiran (update) dengan tautan pada berita yang belum terverifikasi.</li>
      </ul>

      <h2 style="font-family:'Fraunces', serif; font-size:23px; margin:32px 0 12px;">3. Isi Buatan Pengguna (User Generated Content)</h2>
      <ul style="margin-bottom:20px; padding-left:22px;">
        <li style="margin-bottom:10px;">Media siber wajib mencantumkan syarat dan ketentuan mengenai Isi Buatan Pengguna yang tidak bertentangan dengan UU Pers dan Kode Etik Jurnalistik, ditempatkan secara terang dan jelas.</li>
        <li style="margin-bottom:10px;">Setiap pengguna wajib melakukan registrasi keanggotaan dan log-in terlebih dahulu untuk dapat mempublikasikan Isi Buatan Pengguna.</li>
        <li style="margin-bottom:10px;">
          Dalam registrasi, pengguna wajib menyetujui secara tertulis bahwa Isi Buatan Pengguna yang dipublikasikan: tidak memuat isi bohong, fitnah, sadis, dan cabul; tidak memuat prasangka dan kebencian terkait suku, agama, ras, dan antargolongan (SARA) serta tidak menganjurkan kekerasan; dan tidak diskriminatif atas dasar jenis kelamin dan bahasa, serta tidak merendahkan martabat orang lemah, miskin, sakit, cacat jiwa, atau cacat jasmani.
        </li>
        <li style="margin-bottom:10px;">Media siber memiliki kewenangan mutlak untuk mengedit atau menghapus Isi Buatan Pengguna yang melanggar ketentuan di atas.</li>
        <li style="margin-bottom:10px;">Media siber wajib menyediakan mekanisme pengaduan yang mudah diakses pengguna.</li>
        <li style="margin-bottom:10px;">Media siber wajib menyunting, menghapus, atau melakukan tindakan koreksi atas Isi Buatan Pengguna yang dilaporkan dan melanggar ketentuan, paling lambat 2×24 jam setelah pengaduan diterima.</li>
        <li style="margin-bottom:10px;">Media siber yang telah memenuhi ketentuan di atas tidak dibebani tanggung jawab atas masalah yang timbul akibat Isi Buatan Pengguna yang melanggar ketentuan; sebaliknya, media siber bertanggung jawab jika tidak mengambil tindakan koreksi setelah batas waktu tersebut.</li>
      </ul>

      <h2 style="font-family:'Fraunces', serif; font-size:23px; margin:32px 0 12px;">4. Ralat, Koreksi, dan Hak Jawab</h2>
      <ul style="margin-bottom:20px; padding-left:22px;">
        <li style="margin-bottom:10px;">Ralat, koreksi, dan hak jawab mengacu pada UU Pers, Kode Etik Jurnalistik, dan Pedoman Hak Jawab yang ditetapkan Dewan Pers.</li>
        <li style="margin-bottom:10px;">Ralat, koreksi, dan/atau hak jawab wajib ditautkan pada berita yang diralat, dikoreksi, atau diberi hak jawab, disertai waktu pemuatannya.</li>
        <li style="margin-bottom:10px;">Bila suatu berita disebarluaskan media siber lain: tanggung jawab media pembuat berita terbatas pada berita yang dipublikasikan di medianya sendiri; koreksi yang dilakukan media pembuat berita juga harus dilakukan media lain yang mengutipnya; dan media yang tidak melakukan koreksi bertanggung jawab penuh atas akibat hukum dari berita yang tidak dikoreksinya.</li>
        <li style="margin-bottom:10px;">Sesuai UU Pers, media siber yang tidak melayani hak jawab dapat dijatuhi sanksi pidana denda paling banyak Rp500.000.000 (lima ratus juta rupiah).</li>
      </ul>

      <h2 style="font-family:'Fraunces', serif; font-size:23px; margin:32px 0 12px;">5. Pencabutan Berita</h2>
      <ul style="margin-bottom:20px; padding-left:22px;">
        <li style="margin-bottom:10px;">Berita yang sudah dipublikasikan tidak dapat dicabut karena alasan penyensoran dari pihak luar redaksi, kecuali terkait masalah SARA, kesusilaan, masa depan anak, pengalaman traumatik korban, atau pertimbangan khusus lain yang ditetapkan Dewan Pers.</li>
        <li style="margin-bottom:10px;">Media siber lain wajib mengikuti pencabutan kutipan berita dari media asal yang telah dicabut.</li>
        <li style="margin-bottom:10px;">Pencabutan berita wajib disertai alasan pencabutan dan diumumkan kepada publik.</li>
      </ul>

      <h2 style="font-family:'Fraunces', serif; font-size:23px; margin:32px 0 12px;">6. Iklan</h2>
      <ul style="margin-bottom:20px; padding-left:22px;">
        <li style="margin-bottom:10px;">Media siber wajib membedakan dengan tegas antara produk berita dan iklan.</li>
        <li style="margin-bottom:10px;">Setiap konten yang merupakan iklan dan/atau berbayar wajib mencantumkan keterangan "advertorial", "iklan", "ads", "sponsored", atau kata lain yang menjelaskan bahwa konten tersebut adalah iklan.</li>
      </ul>

      <h2 style="font-family:'Fraunces', serif; font-size:23px; margin:32px 0 12px;">7. Hak Cipta</h2>
      <p style="margin-bottom:20px;">Media siber wajib menghormati hak cipta sebagaimana diatur dalam peraturan perundang-undangan yang berlaku.</p>

      <h2 style="font-family:'Fraunces', serif; font-size:23px; margin:32px 0 12px;">8. Pencantuman Pedoman</h2>
      <p style="margin-bottom:20px;">Media siber wajib mencantumkan Pedoman Pemberitaan Media Siber ini di medianya secara terang dan jelas.</p>

      <h2 style="font-family:'Fraunces', serif; font-size:23px; margin:32px 0 12px;">9. Sengketa</h2>
